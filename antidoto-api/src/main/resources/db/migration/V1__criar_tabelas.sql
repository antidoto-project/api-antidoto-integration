-- Antídoto — schema do MVP (MVP-01 §4.2), em SQL do PostgreSQL.
-- Roda igual no Postgres do Render e no H2 (modo PostgreSQL) do computador e dos testes.
-- Diferenças em relação ao DDL Oracle do MVP-01: BIGINT/VARCHAR/BOOLEAN no lugar de
-- NUMBER/VARCHAR2, DOUBLE PRECISION nas coordenadas e TIMESTAMP WITH TIME ZONE nas datas (Instant).

CREATE TABLE usuarios (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        VARCHAR(120) NOT NULL,
  email       VARCHAR(160) NOT NULL,
  senha_hash  VARCHAR(100) NOT NULL,
  telefone    VARCHAR(11),
  perfil      VARCHAR(10)  NOT NULL,
  criado_em   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT uk_usuarios_email UNIQUE (email),
  CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('CIDADAO', 'GESTOR'))
);

CREATE TABLE unidades_saude (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome          VARCHAR(160)     NOT NULL,
  tipo          VARCHAR(10)      NOT NULL,
  endereco      VARCHAR(250)     NOT NULL,
  telefone      VARCHAR(11)      NOT NULL,
  latitude      DOUBLE PRECISION NOT NULL,
  longitude     DOUBLE PRECISION NOT NULL,
  atende_24h    BOOLEAN          NOT NULL,
  ativa         BOOLEAN          DEFAULT TRUE NOT NULL,
  atualizado_em TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT ck_unidades_tipo CHECK (tipo IN ('HOSPITAL', 'UPA', 'UBS'))
);

CREATE TABLE unidade_soros (
  unidade_id BIGINT      NOT NULL,
  soro       VARCHAR(20) NOT NULL,
  CONSTRAINT pk_unidade_soros PRIMARY KEY (unidade_id, soro),
  CONSTRAINT fk_unidade_soros FOREIGN KEY (unidade_id) REFERENCES unidades_saude (id)
);

CREATE TABLE ocorrencias (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id     BIGINT           NOT NULL,
  unidade_id     BIGINT,
  tipo_animal    VARCHAR(10)      NOT NULL,
  faixa_etaria   VARCHAR(10)      NOT NULL,
  hora_picada    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  latitude       DOUBLE PRECISION NOT NULL,
  longitude      DOUBLE PRECISION NOT NULL,
  urgencia       VARCHAR(10)      NOT NULL,
  motivos        VARCHAR(500)     NOT NULL,
  status_resumo  VARCHAR(15)      NOT NULL,
  resumo         VARCHAR(2000),
  criado_em      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_ocorrencias_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id),
  CONSTRAINT fk_ocorrencias_unidade FOREIGN KEY (unidade_id) REFERENCES unidades_saude (id),
  CONSTRAINT ck_ocorrencias_urgencia CHECK (urgencia IN ('EMERGENCIA', 'ALTA', 'MODERADA')),
  CONSTRAINT ck_ocorrencias_status CHECK (status_resumo IN ('PENDENTE', 'PRONTO', 'MODELO_PADRAO'))
);

CREATE TABLE ocorrencia_sintomas (
  ocorrencia_id BIGINT      NOT NULL,
  sintoma       VARCHAR(30) NOT NULL,
  CONSTRAINT pk_ocorrencia_sintomas PRIMARY KEY (ocorrencia_id, sintoma),
  CONSTRAINT fk_ocorrencia_sintomas FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencias (id)
);

CREATE TABLE avistamentos (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id    BIGINT           NOT NULL,
  tipo_animal   VARCHAR(10)      NOT NULL,
  local_avist   VARCHAR(15)      NOT NULL,
  latitude      DOUBLE PRECISION NOT NULL,
  longitude     DOUBLE PRECISION NOT NULL,
  data_hora     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  observacao    VARCHAR(500),
  criado_em     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
  atualizado_em TIMESTAMP(6) WITH TIME ZONE,
  CONSTRAINT fk_avistamentos_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id)
);

CREATE INDEX ix_avistamentos_usuario ON avistamentos (usuario_id, criado_em);
CREATE INDEX ix_ocorrencias_usuario ON ocorrencias (usuario_id, criado_em);
